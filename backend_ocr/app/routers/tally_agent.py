# ── Schemas ────────────────────────────────────────────────────────────────────

class PairRequest(BaseModel):
    token: str
    agent_version: str = "unknown"


class PairResponse(BaseModel):
    api_key: str
    tenant_name: str


class IngestRequest(BaseModel):
    agent_version: str = "unknown"
